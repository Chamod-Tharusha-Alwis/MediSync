"""Serve the unchanged ml-engine/app.py on 127.0.0.1 for the offline demo-seed proof only.

No .env is read (dotenv.load_dotenv is replaced with a no-op, as in ml-engine/evaluation/eval_common.py),
the SQLite path is a fresh temporary file, and INTERNAL_API_KEY must be supplied by the caller
(a random value generated by prove_offline.cjs). Synthetic demonstration data only.

Usage:  python server/scripts/demo/ml_engine_local.py <port>
"""
import contextlib
import io
import os
import sys
import tempfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..'))
ML_DIR = os.path.join(ROOT, 'ml-engine')


def main():
    port = int(sys.argv[1])
    if not os.environ.get('INTERNAL_API_KEY'):
        raise SystemExit('INTERNAL_API_KEY must be provided by the caller')
    import dotenv
    dotenv.load_dotenv = lambda *args, **kwargs: False
    os.environ['MEDISYNC_ML_DB_PATH'] = os.path.join(tempfile.mkdtemp(prefix='medisync_demo_'), 'demo_ml.db')
    os.environ.pop('MEDISYNC_ML_QA', None)
    sys.path.insert(0, ML_DIR)
    with contextlib.redirect_stdout(io.StringIO()):
        import app as engine
    from werkzeug.serving import run_simple
    print(f'ML_ENGINE_READY {port}', flush=True)
    run_simple('127.0.0.1', port, engine.app, threaded=True, use_reloader=False)


if __name__ == '__main__':
    main()
