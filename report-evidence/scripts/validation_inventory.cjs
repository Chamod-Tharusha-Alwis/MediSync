#!/usr/bin/env node
// Writes report-evidence/03_validation_routes.md: every API route (from the repo's own inventory, the same one
// that server/tests/testMatrixInventory.test.js pins at 228) with its middleware and the 4xx responses its handler
// can return, plus Flask endpoints and client form constraints. Static reading only; nothing is executed.
// Usage (repo root): node report-evidence/scripts/validation_inventory.cjs
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..', '..');
const { inventory } = require(path.join(ROOT, 'scripts', 'buildTestMatrix.cjs'));
const read = f => fs.readFileSync(path.join(ROOT, f), 'utf8').replace(/\r\n/g, '\n');
const cell = s => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

// 4xx responses inside one handler body: status code + error/code text.
function failures(body) {
  const out = new Set();
  const re = /status\((4\d\d)\)\s*\.json\(\s*\{([^}]{0,220})/g;
  let m;
  while ((m = re.exec(body))) {
    const code = (m[2].match(/code\s*:\s*['"`]([A-Z0-9_]+)['"`]/) || [])[1];
    const err = (m[2].match(/error\s*:\s*['"`]([^'"`]{1,70})['"`]/) || [])[1];
    out.add(`${m[1]} ${code || err || '(dynamic)'}`);
  }
  // Services that throw typed errors with a status (DispenseError, ItemError, ClinicalCommandError).
  const re2 = /fail\(\s*['"`]([A-Z0-9_]+)['"`][^;]*?,\s*(4\d\d)\s*\)/g;
  while ((m = re2.exec(body))) out.add(`${m[2]} ${m[1]}`);
  return [...out];
}

// Body of `exports.name = ...` or `const name = ...`/`function name` in a controller file.
function handlerBody(file, name) {
  const src = read(file);
  const starts = [new RegExp(`exports\\.${name}\\s*=`), new RegExp(`(?:const|let)\\s+${name}\\s*=`), new RegExp(`function\\s+${name}\\s*\\(`)];
  let at = -1;
  for (const r of starts) { const m = src.match(r); if (m) { at = m.index; break; } }
  if (at < 0) return '';
  const next = src.slice(at + 1).search(/\nexports\.[A-Za-z_$]+\s*=|\n(?:async\s+)?function\s+[A-Za-z_$]+\s*\(/);
  return src.slice(at, next < 0 ? undefined : at + 1 + next);
}

function controllerFile(routeFile, objName) {
  const src = read(routeFile);
  const m = src.match(new RegExp(`(?:const|let)\\s+${objName}\\s*=\\s*require\\(['"]([^'"]+)['"]\\)`)) ||
            src.match(new RegExp(`(?:const|let)\\s*\\{[^}]*\\b${objName}\\b[^}]*\\}\\s*=\\s*require\\(['"]([^'"]+)['"]\\)`));
  if (!m) return null;
  const p = path.join(path.dirname(routeFile), m[1]).replace(/\\/g, '/');
  return [p + '.js', p, p + '/index.js'].find(f => fs.existsSync(path.join(ROOT, f))) || null;
}

const MW = [
  [/protect\(\s*\[([^\]]*)\]\s*\)|protect\(\)/, m => (m[1] !== undefined ? `protect(${m[1].replace(/['"\s]/g, '') || 'any role'})` : 'protect(any role)')],
  [/patientConsent|requirePatientConsent/, () => 'patient consent token'],
  [/clinicalWriteAuthorization/, () => 'clinical write authorization'],
  [/validate[A-Z][A-Za-z]*/, m => m[0]],
  [/[A-Za-z]*[Ll]imiter\b/, m => m[0]],
  [/upload\.|multer|profileImageAdmission/, () => 'upload admission'],
  [/verifiedAuth|requireVerified/, () => 'verified account'],
];

function main() {
  const inv = inventory(ROOT);
  const api = inv.rows.filter(r => r.kind === 'API');
  const lines = [];
  lines.push('# Route-by-route validation table (generated)', '',
    `Generated by \`report-evidence/scripts/validation_inventory.cjs\` from commit \`${require('child_process').execSync('git rev-parse --short HEAD', { cwd: ROOT, encoding: 'utf8' }).trim()}\` on ${new Date().toISOString()}.`,
    `Routes: **${api.length}** (the repo's own inventory, \`scripts/buildTestMatrix.cjs\`, which \`server/tests/testMatrixInventory.test.js\` pins at 228).`, '',
    '- *Role*: role restriction declared on the route (from the inventory).',
    '- *Middleware*: checks that run before the handler.',
    '- *4xx responses*: every `res.status(4xx).json(...)` and typed `fail(CODE, ..., 4xx)` found in the handler body (static scan; responses produced in helper modules the handler calls are not listed, so this is a lower bound).',
    '- Joi is **not used**: `joi` is declared in `server/package.json` but no file in `server/src` imports it. Validation is hand-written in middleware, controllers, services and Mongoose schemas.', '',
    '| # | Method | Path | Role | Middleware | Handler | 4xx responses found |', '|---|---|---|---|---|---|---|');
  api.sort((a, b) => a.route.localeCompare(b.route) || a.method.localeCompare(b.method)).forEach((r, i) => {
    const src = read(r.file).split('\n');
    let stmt = '';
    for (let k = r.line - 1; k < Math.min(src.length, r.line + 6); k++) { stmt += src[k] + '\n'; if (/\);\s*$/.test(src[k])) break; }
    const mws = [];
    for (const [re, fmt] of MW) { const m = stmt.match(re); if (m) mws.push(fmt(m)); }
    // Named wrappers such as `const dispensingAuth = protect(['pharmacist', ...])`.
    for (const a of src.join('\n').matchAll(/(?:const|let)\s+([A-Za-z_$]+)\s*=\s*protect\(\s*\[([^\]]*)\]\s*\)/g)) {
      if (new RegExp(`[,(]\\s*${a[1]}\\s*[,)]`).test(stmt)) mws.unshift(`${a[1]} = protect(${a[2].replace(/['"\s]/g, '')})`);
    }
    let fails = [];
    const hm = String(r.name || '').match(/^([A-Za-z_$]+)\.([A-Za-z_$]+)$/);
    if (hm) { const cf = controllerFile(r.file, hm[1]); if (cf) fails = failures(handlerBody(cf, hm[2])); }
    else if (r.name) { const cf = controllerFile(r.file, r.name); if (!cf) fails = failures(handlerBody(r.file, r.name) || stmt); }
    lines.push(`| ${i + 1} | ${r.method} | \`${cell(r.route)}\` | ${cell(r.role || '-')} | ${cell(mws.join(', ') || '-')} | \`${cell(r.name || '(inline)')}\` ${cell(r.file.replace('server/src/', ''))}:${r.line} | ${cell(fails.slice(0, 8).join('; ') || 'none found in handler body')}${fails.length > 8 ? `; +${fails.length - 8} more` : ''} |`);
  });

  // Flask service inputs.
  const app = read('ml-engine/app.py').split('\n');
  lines.push('', '## Flask ML service endpoints (`ml-engine/app.py`)', '', '| Line | Method(s) | Path | Input checks returning 4xx (static scan of the function body) |', '|---|---|---|---|');
  app.forEach((l, i) => {
    const m = l.match(/@app\.route\(\s*['"]([^'"]+)['"](?:.*methods\s*=\s*\[([^\]]*)\])?/);
    if (!m) return;
    let j = i + 1; while (j < app.length && !/^def /.test(app[j])) j++;
    let k = j + 1; while (k < app.length && !/^(@app\.route|def |[A-Za-z_])/.test(app[k])) k++;
    const body = app.slice(j, k).join('\n');
    const errs = new Set(); let e; const re = /jsonify\(\s*\{\s*['"]error['"]\s*:\s*['"]([^'"]{1,60})['"][^)]*\)\s*,\s*(4\d\d)/g;
    while ((e = re.exec(body))) errs.add(`${e[2]} ${e[1]}`);
    lines.push(`| ${i + 1} | ${cell((m[2] || "'GET'").replace(/['"\s]/g, ''))} | \`${m[1]}\` | ${cell([...errs].join('; ') || 'none found')} |`);
  });

  // Client form constraints.
  lines.push('', '## Client-side form checks (HTML constraint attributes per file)', '',
    '| File | required | pattern | minLength / maxLength | min / max | type=email / tel / number |', '|---|---|---|---|---|---|');
  const walk = d => fs.readdirSync(path.join(ROOT, d), { withFileTypes: true }).flatMap(x => x.isDirectory() ? (/(__|tests?$)/.test(x.name) ? [] : walk(path.join(d, x.name))) : (/\.jsx$/.test(x.name) ? [path.join(d, x.name).replace(/\\/g, '/')] : []));
  for (const f of walk('client/src')) {
    const s = read(f);
    const c = re => (s.match(re) || []).length;
    const row = [c(/\brequired\b(?!:)/g), c(/\bpattern=/g), c(/\b(minLength|maxLength)=/g), c(/\b(min|max)=["{]/g), c(/type=["'](email|tel|number)["']/g)];
    if (row.some(Boolean)) lines.push(`| ${f.replace('client/src/', '')} | ${row.join(' | ')} |`);
  }
  fs.writeFileSync(path.join(ROOT, 'report-evidence', '03_validation_routes.md'), lines.join('\n') + '\n');
  console.log('routes', api.length);
}
main();
